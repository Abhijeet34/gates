#!/bin/sh
# The commit-msg hook refuses an AI-agent attribution line and passes the rest.
#
#   system-maintenance/git-hooks/test-commit-msg.sh
#
# Runs the hook directly on a message file; no repository or HOME is touched.
set -u

HOOK=$(cd "$(dirname "$0")" && pwd -P)/commit-msg
[ -x "$HOOK" ] || { echo "test-commit-msg: $HOOK is not executable" >&2; exit 2; }
DIR=$(mktemp -d "${TMPDIR:-/tmp}/commit-msg-test.XXXXXX") || exit 2
trap '[ -n "${DIR:-}" ] && [ -d "$DIR" ] && rm -rf "$DIR"' EXIT

fails=0
# expect <refuse|pass> <label> <message text>
expect() {
    want=$1 label=$2
    printf '%s\n' "$3" >"$DIR/msg"
    out=$("$HOOK" "$DIR/msg" 2>&1)
    rc=$?
    if [ "$want" = refuse ] && [ "$rc" -ne 0 ] && [ -n "$out" ]; then
        printf 'ok   refused  %s\n' "$label"
    elif [ "$want" = pass ] && [ "$rc" -eq 0 ]; then
        printf 'ok   passed   %s\n' "$label"
    else
        printf 'FAIL %s: wanted %s, rc=%s, output=%s\n' "$label" "$want" "$rc" "$out" >&2
        fails=$((fails + 1))
    fi
}

body='feat: thing

Why it changed.
'

for t in \
    'Co-authored-by: Claude <noreply@anthropic.com>' \
    'Co-Authored-By: Claude Opus 5 <noreply@anthropic.com>' \
    'Co-authored-by: Codex <codex@openai.com>' \
    'Co-authored-by: ChatGPT <noreply@openai.com>' \
    'Co-authored-by: Gemini <gemini@google.com>' \
    'Co-authored-by: Cursor Agent <cursoragent@cursor.com>' \
    'Co-authored-by: Copilot <175728472+Copilot@users.noreply.github.com>' \
    'Co-Authored-By: Warp <agent@warp.dev>' \
    'Co-authored-by: Kimi <kimi@moonshot.cn>' \
    'Co-authored-by: DeepSeek <bot@deepseek.com>' \
    'Co-authored-by: Qwen <qwen@alibabacloud.com>' \
    'Co-authored-by: GLM <glm@zhipuai.cn>' \
    'Co-authored-by: Grok <grok@x.ai>' \
    'Co-authored-by: opencode <noreply@opencode.ai>' \
    'Co-authored-by: Devin AI <devin-ai-integration[bot]@users.noreply.github.com>' \
    'Co-authored-by: aider (gpt-4o) <noreply@aider.chat>' \
    '🤖 Generated with [Claude Code](https://claude.com/claude-code)' \
    'Generated with Codex' \
    'Generated by Gemini CLI'; do
    expect refuse "$t" "$body
$t"
done

expect pass 'human co-author' "$body
Co-authored-by: Jane Doe <jane@example.com>"
expect pass 'human co-author, mixed case trailer' "$body
Co-Authored-By: Sam Lee <sam@example.org>"
expect pass 'plain message' "$body"
expect pass 'comment line naming an agent' "$body
# Co-authored-by: Claude <noreply@anthropic.com>"
expect pass 'prose mentioning an agent' 'docs: explain how Claude Code hooks run

Generated files are skipped.'

[ "$fails" -eq 0 ] || { echo "test-commit-msg: $fails FAILED" >&2; exit 1; }
echo "test-commit-msg: all passed"
